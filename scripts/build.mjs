import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(import.meta.url);
const ascVersion = require("assemblyscript/package.json").version;
const asconfig = JSON.parse(readFileSync(join(root, "asconfig.json"), "utf8"));

execFileSync(process.execPath, [join(root, "node_modules/assemblyscript/bin/asc.js"), "--config", "asconfig.json"], { cwd: root, stdio: "inherit" });

const wasm = readFileSync(join(root, asconfig.options.outFile));

const sourceHash = createHash("sha256");
for (const file of readdirSync(join(root, "assembly")).sort()) {
    sourceHash.update(file).update(readFileSync(join(root, "assembly", file)));
}

sourceHash.update(JSON.stringify(asconfig));

let gitRevision = "unknown";
let gitDirty = true;
try {
    gitRevision = execFileSync("git", ["rev-parse", "HEAD"], { cwd: root }).toString().trim();
    gitDirty = execFileSync("git", ["status", "--porcelain", "--", "assembly", "asconfig.json"], { cwd: root }).toString().trim() !== "";
} catch {}

const buildInfo = {
    compiler: `assemblyscript@${ascVersion}`,
    options: asconfig.options,
    sourceSha256: sourceHash.digest("hex"),
    wasmSha256: createHash("sha256").update(wasm).digest("hex"),
    wasmBytes: wasm.length,
    gitRevision,
    gitDirty
};

mkdirSync(join(root, "src/generated"), { recursive: true });
writeFileSync(join(root, "src/generated/math-wasm.js"),
    "// Generated by scripts/build.mjs. Do not edit.\n" +
    `export const buildInfo = ${JSON.stringify(buildInfo, null, 4)};\n\n` +
    `export const wasmBase64 = "${wasm.toString("base64")}";\n`);

console.log(`math.wasm ${wasm.length} bytes, sha256 ${buildInfo.wasmSha256.slice(0, 16)}`);
